"""Diagnostics for treatment/control chromosome-name compatibility."""


def check_chromosome_names(treatment_names, control_names, error_stream):
    """Require at least one shared name, reporting both sets on failure."""
    treatment_names = set(treatment_names)
    control_names = set(control_names)
    if treatment_names.intersection(control_names):
        return

    error_stream("No common chromosome names can be found from treatment and control!")
    error_stream("Please make sure that the treatment and control alignment files were generated by using the same genome assembly!")
    for label, names in (("treatment", treatment_names),
                         ("control", control_names)):
        # Escaping invalid UTF-8 keeps even malformed names diagnosable.
        display_names = sorted(name.decode("utf-8", errors="backslashreplace")
                               if isinstance(name, bytes) else str(name)
                               for name in names)
        error_stream("Chromosome names in %s: %s" %
                     (label, ",".join(display_names)))
    raise SystemExit(1)
