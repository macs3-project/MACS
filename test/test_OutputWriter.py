def test_diag_write_exact(tmp_path):
    out = tmp_path / "diag.txt"
    diag_write(str(out), [["10-20", 5, 0.123, 0.456, 0.789],
                          ["20-inf", 12, 1.0, 99.994, 0.0]])
    # three metric columns -> sampling levels 90%, 80%, 70%; "%.2f" each
    assert out.read_text() == (
        "FC range\t# of Peaks\tcover by sampling 90%\t80%\t70%\n"
        "10-20\t5\t0.12\t0.46\t0.79\n"
        "20-inf\t12\t1.00\t99.99\t0.00\n")


def test_diag_write_no_metrics(tmp_path):
    out = tmp_path / "diag.txt"
    diag_write(str(out), [("all", 3.7)])
    # "%d" truncates 3.7 to 3
    assert out.read_text() == "FC range\t# of Peaks\tcover by sampling %\nall\t3\n"


def test_diag_write_eleven_levels(tmp_path):
    out = tmp_path / "diag.txt"
    diag_write(str(out), [["x", 1] + [0.5] * 11])
    levels = "%\t".join(str(90 - 10 * i) for i in range(11)) + "%"
    assert out.read_text().splitlines()[0] == \
        "FC range\t# of Peaks\tcover by sampling " + levels
    assert levels.endswith("0%\t-10%")


def test_diag_write_empty_raises(tmp_path):
    with pytest.raises(IndexError):
        diag_write(str(tmp_path / "diag.txt"), [])


def test_diag_write_ragged_rows_raise(tmp_path):
    with pytest.raises(TypeError, match="not enough arguments"):
        diag_write(str(tmp_path / "diag.txt"), [["a", 1, 0.5], ["b", 2]])


