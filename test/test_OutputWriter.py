def _model(**kwargs):
    """Fake PeakModel with the attribute types of a real one: int32 lines,
    float64 correlations, int alternative_d list."""
    base = dict(plus_line=np.array([1, 2, 1], dtype="i4"),
                minus_line=np.array([0, 1, 3], dtype="i4"),
                ycorr=np.array([0.25, 0.5, -0.125]),
                xcorr=np.array([-1.0, 0.0, 1.0]),
                alternative_d=[100, 150],
                d=100)
    base.update(kwargs)
    return SimpleNamespace(**base)


def _r_script(p, m, ycorr, xcorr, altd_comma_space, name, altd_comma):
    return ("# R script for Peak Model\n"
            "#  -- generated by MACS\n"
            "p <- c(%s)\n"
            "m <- c(%s)\n"
            "ycorr <- c(%s)\n"
            "xcorr <- c(%s)\n"
            "altd  <- c(%s)\n"
            "x <- seq.int((length(p)-1)/2*-1,(length(p)-1)/2)\n"
            "pdf('%s_model.pdf',height=6,width=6)\n"
            "plot(x,p,type='l',col=c('red'),main='Peak Model',"
            "xlab='Distance to the middle',ylab='Percentage')\n"
            "lines(x,m,col=c('blue'))\n"
            "legend('topleft',c('forward tags','reverse tags'),lty=c(1,1,1),"
            "col=c('red','blue'))\n"
            "plot(xcorr,ycorr,type='l',col=c('black'),main='Cross-Correlation',"
            "xlab='Lag between + and - tags',ylab='Correlation')\n"
            "abline(v=altd,lty=2,col=c('red'))\n"
            "legend('topleft','alternative lag(s)',lty=2,col='red')\n"
            "legend('right','alt lag(s) : %s',bty='n')\n"
            "dev.off()\n"
            % (p, m, ycorr, xcorr, altd_comma_space, name, altd_comma))


def test_model2r_script_exact(tmp_path):
    out = tmp_path / "x_model.r"
    model2r_script(_model(), str(out), "sample")
    # p = [1, 2, 1] -> 100 * p / 4 = [25, 50, 25] percent
    # m = [0, 1, 3] -> 100 * m / 4 = [0, 25, 75] percent
    assert out.read_text() == _r_script("25.0,50.0,25.0", "0.0,25.0,75.0",
                                        "0.25,0.5,-0.125", "-1.0,0.0,1.0",
                                        "100, 150", "sample", "100,150")


def test_model2r_script_plain_lists_single_alt_d(tmp_path):
    out = tmp_path / "m.r"
    model = _model(plus_line=[3, 1], minus_line=[1, 1, 2, 0],
                   ycorr=[1, 2], xcorr=[5, 6], alternative_d=[200])
    model2r_script(model, str(out), "a/b")
    # p: [75, 25]; m: 100 * [1, 1, 2, 0] / 4 = [25, 25, 50, 0]; only the
    # first len(p) values of m are written
    assert out.read_text() == _r_script("75.0,25.0", "25.0,25.0", "1,2",
                                        "5,6", "200", "a/b", "200")


def test_model2r_script_empty_lines(tmp_path):
    out = tmp_path / "m.r"
    model2r_script(_model(plus_line=[], minus_line=[], ycorr=[], xcorr=[],
                          alternative_d=[]), str(out), "e")
    assert out.read_text() == _r_script("", "", "", "", "", "e", "")


def test_model2r_script_zero_sum_raises(tmp_path):
    with pytest.raises(ZeroDivisionError):
        model2r_script(_model(plus_line=[0, 0], minus_line=[1, 1]),
                       str(tmp_path / "m.r"), "z")


def test_model2r_script_overwrites(tmp_path):
    out = tmp_path / "m.r"
    out.write_text("old\n" * 100)
    model2r_script(_model(), str(out), "sample")
    assert out.read_text().startswith("# R script for Peak Model\n")
    assert "old" not in out.read_text()


def test_model2r_script_missing_attribute(tmp_path):
    with pytest.raises(AttributeError):
        model2r_script(SimpleNamespace(plus_line=[1]), str(tmp_path / "m.r"),
                       "x")


