class FakeTrack:
    """Minimal stand-in for FWTrack: ``get_chr_names`` and
    ``get_locations_by_chr`` returning (plus, minus) int32 arrays."""

    def __init__(self, tags):
        self._tags = tags

    def get_chr_names(self):
        return set(self._tags)

    def get_locations_by_chr(self, chrom):
        return (np.array(self._tags[chrom], dtype="i4"),
                np.array([], dtype="i4"))


def _gunzip(path):
    with gzip.open(path, "rt") as fh:
        return fh.read()


def _wig_track_line(prefix, chrom, space=10):
    return ('track type=wiggle_0 name="%s_%s" description="Extended tag '
            'pileup from MACS version %s for every %d bp"\n'
            % (prefix, chrom, MACS_VERSION, space))


def _bdg_track_line(prefix, chrom):
    return ('track type=bedGraph name="%s_%s" description="Extended tag '
            'pileup from MACS version %s"\n' % (prefix, chrom, MACS_VERSION))


