def _log_text(record):
    """Message of a log record without MemoryLogger's "[N MB] " prefix.

    OutputWriter does not import MACS3.Utilities.Logger itself, so its
    logger is a MemoryLogger only when another MACS3 module imported
    Logger first (as in a real macs3 run, or earlier tests in the same
    session). Stripping the prefix keeps these tests order-independent.
    """
    return re.sub(r"^\[\d+ MB\] ", "", record.getMessage())


def test_zwig_write_no_chromosomes(tmp_path):
    sub = tmp_path / "wig"
    zwig_write(FakeTrack({}), str(sub), "pre", 20)
    assert sub.is_dir()
    assert list(sub.iterdir()) == []


def test_zwig_write_single_no_chromosomes(tmp_path, caplog):
    sub = tmp_path / "wig"
    with caplog.at_level(logging.INFO, logger="MACS3.IO.OutputWriter"):
        zwig_write(FakeTrack({}), str(sub), "pre_afterfiting", 20, space=25,
                   single=True)
    assert [p.name for p in sub.iterdir()] == ["pre_afterfiting_all.wig.gz"]
    assert _gunzip(sub / "pre_afterfiting_all.wig.gz") == \
        _wig_track_line("pre", "all", space=25)
    assert [_log_text(r) for r in caplog.records] == \
        ["write to a wiggle file", "compress the wiggle file using gzip..."]


def test_zwig_write_existing_directory_raises(tmp_path):
    with pytest.raises(FileExistsError):
        zwig_write(FakeTrack({}), str(tmp_path), "pre", 20)


def test_zwig_write_chromosome_without_tags(tmp_path):
    sub = tmp_path / "wig"
    zwig_write(FakeTrack({"chr1": []}), str(sub), "pre", 20)
    assert [p.name for p in sub.iterdir()] == ["pre_chr1.wig.gz"]
    assert _gunzip(sub / "pre_chr1.wig.gz") == \
        _wig_track_line("pre", "chr1") + "variableStep chrom=chr1 span=10\n"


